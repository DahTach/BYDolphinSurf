import { ChangeDetectionStrategy, Component, ElementRef, OnDestroy, computed, effect, input, signal, untracked, viewChild } from '@angular/core';

import { prefersReducedMotion } from '../../shared/motion';

/* Reusable Onda M3E wavy progress primitive (specs/design-system "Wavy progress
   indicator (M3E)", rifiniture-e D4). Two shapes on ONE motion contract:
   - `bar` (default): linear sine-wave bar (mirrors ui-drafts/e2-stat-grid.html
     variant B). Track and fill share ONE canonical sine-wave path (midline y=6,
     x-extent 2→198 so the round caps stay inside the viewBox, first bump up,
     half-period 14 → wavelength ≈28px, stroke-width 4, round caps), rendered
     `w-full h-3` with the default preserveAspectRatio. `pathLength="1000"`
     normalizes the length: the fill is carved with the `stroke-dasharray` PAIR
     `P 1000` — `P = round(value% × 10)`, floored at exactly 45 for any live
     value so tiny fills keep a visible wave head and capped at 1000 (≥100% →
     `1000 1000`, the periodic path closes on its start point so the seam hides);
     0% renders EMPTY (`0 1000`) — a zero-length dash with a round cap paints a
     dot, so the empty state switches the fill to butt caps (nothing renders).
     Two speeds on one element: the entrance fill animates the dash from
     `0 1000` to `P 1000` over 650ms `--d-bar` `--e-spring` on activation only
     (playFill(), once); later data edits transition `stroke-dasharray` over
     `--d-small` `--e-emph` and never replay the entrance.
   - `ring`: M3E CIRCULAR wavy gauge (the material_3_expressive gemini gauge
     concepts on our pinned geometry). viewBox 0 0 120 120 rendered
     `w-[120px] h-[120px]`, stroke 6.5 round caps AND joins on both arcs. The
     ACTIVE arc is the radial sine wave `r(θ) = 52 + 3.5·sin(12θ + phase)` drawn
     ONLY along the active span — 12 o'clock, clockwise, `value% × 3.6°` — with
     the wave amplitude Hann-TAPERED near both endpoints (12% of the span ≈ the
     last ~1–1.5 waves, down to 0 at the tip) so the round caps land level on
     the base circle (crisp heads); the
     TRACK is a smooth (unwavy) arc over the remaining span with the Material 3
     angular gaps at the junctions (16° between path ends ≈ 8° visible after the
     round-cap overhang). Semantics: 0% renders NO active wave (the track closes
     the full circle), any live value keeps a ≥2% wave head (gemini floor 0.02),
     and 100% closes the wavy ring seamlessly — the endpoint tapers and the gaps
     fade out as the sweep approaches 360°.
     The ring geometry depends on the value, so both arcs are regenerated by ONE
     pure function (≤240 samples ≈ 20 per wave) and the progress itself is
     rAF-animated in JS on the token curves (runCount pattern): the entrance
     fills 0 → value over 650ms `--d-bar` `--e-spring` (≈3% overshoot) on
     activation only (playFill(), once); data edits move the progress over 250ms
     `--d-small` `--e-emph` and never replay the entrance. Reduced motion snaps
     to the final state. */

/** Matches the CSS token `--d-bar` (650ms): the entrance fill duration. */
const FILL_MS = 650;

/** Matches the CSS token `--d-small` (250ms): the ring's data-edit duration. */
const EDIT_MS = 250;

/** The canonical sine path — copied verbatim from ui-drafts/e2-stat-grid.html variant B. */
const WAVE_PATH = 'M2 6 Q9 -1 16 6 T30 6 T44 6 T58 6 T72 6 T86 6 T100 6 T114 6 T128 6 T142 6 T156 6 T170 6 T184 6 T198 6';

/* ── Ring gauge geometry (gemini gauge generator concepts, our pinned numbers) ──
   viewBox 0 0 120 120: base circle r=52 at (60, 60); the active radius
   oscillates as `52 + 3.5·sin(12θ + phase)`, θ measured CLOCKWISE from
   12 o'clock (SVG y-down) so the zero crossing sits at 12 o'clock — exactly 12
   whole waves so a full 360° sweep closes seamlessly on its start point (60, 8). */

const RING_CX = 60;
const RING_CY = 60;
const RING_R = 52;
const RING_AMPLITUDE = 3.5;
const RING_WAVES = 12;
/** Gap between the path ENDS at each junction (gemini gapDeg=16): each round cap
    overhangs its endpoint by 3.25px ≈ 3.6° at r=52, so the VISIBLE gap is ≈8°. */
const RING_GAP_DEG = 16;
/** Minimum visible wave head (gemini clamps progress at 0.02): any live value
    draws at least 2% × 3.6° = 7.2° of wavy arc. */
const RING_MIN_PCT = 2;
/** Amplitude taper window at each endpoint: the gemini's "first/last 12% of the
    span", capped at 1.5 waves — on a full-circle span 12% = 43° ≈ 1.4 waves,
    the "~1–1.5 waves" of gentle drop; shorter spans scale the window down so
    their heads stay wavy instead of lens-shaped. */
const RING_TAPER_FRAC = 0.12;
const RING_TAPER_WAVES = 1.5;
/** Taper strength fades over the last 75° of sweep: at 100% the ring closes
    seamlessly (full amplitude across 12 o'clock, gaps gone). */
const RING_CLOSE_DEG = 75;
/** The track arc drops out below this span (gemini: 6°) — gaps close near 100%. */
const RING_MIN_TRACK_DEG = 6;
/** Path sampling around the full circle: 240 points ≈ 20 per wave. */
const RING_SAMPLES = 240;

interface RingArcs {
  /** Wavy active arc from 12 o'clock clockwise — '' at 0% (no active wave). */
  active: string;
  /** Smooth track arc over the remaining span — '' when there is none. */
  track: string;
  /** 0%: the track closes the full circle (no active wave, no gaps). */
  full: boolean;
}

/**
 * The two ring arcs for a value in percent (0–100): the ACTIVE wavy span
 * `max(value, 2)% × 3.6°` with its endpoint tapers, and the TRACK arc between
 * the Material 3 gaps. 100% closes the wavy ring seamlessly.
 */
function ringArcs(percent: number): RingArcs {
  const pct = Math.min(Math.max(percent, 0), 100);
  if (pct <= 0) return { active: '', track: '', full: true };
  const sweep = Math.max(pct, RING_MIN_PCT) * 3.6;
  // Endpoint taper strength → 0 as the ring closes (seamless at 100%).
  const taper = Math.min(Math.max((360 - sweep) / RING_CLOSE_DEG, 0), 1);
  const active = wavyArc(sweep, taper);
  const trackStart = sweep + RING_GAP_DEG;
  const trackEnd = 360 - RING_GAP_DEG;
  const track = trackEnd - trackStart >= RING_MIN_TRACK_DEG ? smoothArc(trackStart, trackEnd) : '';
  return { active, track, full: false };
}

/**
 * Sampled wavy arc from 12 o'clock over `sweepDeg` clockwise: radius
 * `52 + 3.5·env·sin(12θ + phase)`. `taper` (0–1) scales the Hann envelope that
 * falls to 0 over the last 12% of the span (≤1.5 waves) at each end — it passes
 * through ≈40–50% at mid-window and reaches 0 exactly at the endpoint, where
 * the radius is 52 with a purely tangential tangent so the round cap lands
 * level on the base circle (crisp head — the gemini "caps stay level" trick).
 */
function wavyArc(sweepDeg: number, taper: number, phase = 0): string {
  const steps = Math.round(Math.max(48, Math.min(RING_SAMPLES, (sweepDeg / 360) * RING_SAMPLES)));
  // Never taper more than half the span: a minimum head keeps one full-amplitude crest.
  const taperDeg = Math.min(sweepDeg * RING_TAPER_FRAC, (360 / RING_WAVES) * RING_TAPER_WAVES, sweepDeg / 2);
  let d = '';
  for (let i = 0; i <= steps; i++) {
    const deg = (i / steps) * sweepDeg;
    const fade = Math.min(Math.min(deg, sweepDeg - deg) / taperDeg, 1);
    const env = 1 - taper * (0.5 + 0.5 * Math.cos(Math.PI * fade));
    const theta = (deg * Math.PI) / 180;
    const r = RING_R + RING_AMPLITUDE * env * Math.sin(RING_WAVES * theta + phase);
    const a = ((deg - 90) * Math.PI) / 180;
    d += (i === 0 ? 'M' : 'L') + (RING_CX + r * Math.cos(a)).toFixed(2) + ' ' + (RING_CY + r * Math.sin(a)).toFixed(2);
  }
  return d;
}

/** Smooth circular arc between two angles (0° = 12 o'clock, clockwise). */
function smoothArc(startDeg: number, endDeg: number): string {
  const a0 = ((startDeg - 90) * Math.PI) / 180;
  const a1 = ((endDeg - 90) * Math.PI) / 180;
  const sx = RING_CX + RING_R * Math.cos(a0);
  const sy = RING_CY + RING_R * Math.sin(a0);
  const ex = RING_CX + RING_R * Math.cos(a1);
  const ey = RING_CY + RING_R * Math.sin(a1);
  const largeArc = endDeg - startDeg > 180 ? 1 : 0;
  return `M${sx.toFixed(2)} ${sy.toFixed(2)}A${RING_R} ${RING_R} 0 ${largeArc} 1 ${ex.toFixed(2)} ${ey.toFixed(2)}`;
}

/**
 * CSS `cubic-bezier()` evaluated in JS (the runCount precedent) so the ring's
 * two speeds ride the exact token curves: `--e-spring` (entrance, ≈3% overshoot)
 * and `--e-emph` (data edits).
 */
function cubicBezier(x1: number, y1: number, x2: number, y2: number): (t: number) => number {
  const cx = 3 * x1;
  const bx = 3 * (x2 - x1) - cx;
  const ax = 1 - cx - bx;
  const cy = 3 * y1;
  const by = 3 * (y2 - y1) - cy;
  const ay = 1 - cy - by;
  return (t: number) => {
    // Newton–Raphson on x(u) = t, then y(u): 4 iterations are plenty in [0,1].
    let u = t;
    for (let i = 0; i < 4; i++) {
      const x = ((ax * u + bx) * u + cx) * u - t;
      const d = (3 * ax * u + 2 * bx) * u + cx;
      if (Math.abs(x) < 1e-5 || d === 0) break;
      u -= x / d;
    }
    return ((ay * u + by) * u + cy) * u;
  };
}

const EASE_SPRING = cubicBezier(0.34, 1.4, 0.64, 1);
const EASE_EMPH = cubicBezier(0.2, 0, 0, 1);

@Component({
  selector: 'app-wavy-progress',
  changeDetection: ChangeDetectionStrategy.Eager,
  styles: `
    :host {
      display: block;
    }

    /* Data-edit speed by default; the entrance overrides it while it plays. */
    .wavy-fill {
      transition: stroke-dasharray var(--d-small) var(--e-emph);
    }

    .wavy-fill.entering {
      transition: stroke-dasharray var(--d-bar) var(--e-spring);
    }
  `,
  template: `
    @if (shape() === 'ring') {
      <svg viewBox="0 0 120 120" class="w-[120px] h-[120px]" fill="none" aria-hidden="true">
        @if (ringPaths().full) {
          <circle cx="60" cy="60" r="52" class="stroke-surfHiX" stroke-width="6.5" />
        } @else {
          @if (ringPaths().track) {
            <path class="stroke-surfHiX" [attr.d]="ringPaths().track" stroke-width="6.5" stroke-linecap="round" />
          }
          @if (ringPaths().active) {
            <path [class]="fill()" [attr.d]="ringPaths().active" stroke-width="6.5" stroke-linecap="round" stroke-linejoin="round" />
          }
        }
      </svg>
    } @else {
      <svg viewBox="0 0 200 12" class="w-full h-3" fill="none" stroke-width="4" stroke-linecap="round" aria-hidden="true">
        <path class="stroke-surfHiX" [attr.d]="wavePath" pathLength="1000" />
        <path #fillPath [class]="'wavy-fill ' + fill()" [attr.d]="wavePath" pathLength="1000" [attr.stroke-linecap]="emptyDash() ? 'butt' : 'round'" [attr.stroke-dasharray]="displayDash()" />
      </svg>
    }
  `,
})
export class WavyProgress implements OnDestroy {
  /** Value in percent (0–100) — e.g. 18 for 18%. */
  readonly value = input<number>(0);
  /** Fill stroke as a token color class (e.g. 'stroke-prim', 'stroke-onTerC'). */
  readonly fill = input<string>('');
  /** Progress form: the linear bar (default) or the M3E circular wavy ring. */
  readonly shape = input<'bar' | 'ring'>('bar');

  protected readonly wavePath = WAVE_PATH;

  /* ── BAR form: dash-carved fill (unchanged) ── */

  /** The `P 1000` dash pair: empty at 0%, `round(max(value% × 10, 45))` above, capped at 1000. */
  protected readonly dash = computed(() => {
    const pct = this.value();
    return pct <= 0 ? '0 1000' : `${Math.min(Math.round(Math.max(pct * 10, 45)), 1000)} 1000`;
  });

  /** Empty until the activation entrance plays — so no fill paints before its reveal. */
  private readonly entered = signal(false);
  protected readonly displayDash = computed(() => (this.entered() ? this.dash() : '0 1000'));

  /** A zero-length dash paints a round-cap dot: the empty fill gets butt caps instead. */
  protected readonly emptyDash = computed(() => this.displayDash() === '0 1000');

  private readonly fillPath = viewChild('fillPath', { read: ElementRef });
  private enterTimer = 0;

  /* ── RING form: value-driven geometry on a rAF-animated progress ── */

  /** Displayed progress in percent (0–100): rAF-animated towards `value`. */
  private readonly progress = signal(0);
  protected readonly ringPaths = computed(() => ringArcs(this.progress()));
  private raf = 0;

  private played = false;

  /**
   * A data edit during the entrance window drops to the data-edit speed:
   * the `.entering` override is removed as soon as the dash target changes
   * (audit m1) — the base `--d-small` transition takes over from here.
   */
  private readonly dashEdit = effect(() => {
    this.dash();
    untracked(() => {
      if (!this.played || !this.entered() || !this.enterTimer) return;
      clearTimeout(this.enterTimer);
      this.enterTimer = 0;
      const path = this.fillPath()?.nativeElement as SVGPathElement | undefined;
      path?.classList.remove('entering');
    });
  });

  /**
   * Ring data edits regenerate the geometry at the data-edit speed (250ms
   * `--e-emph`) from wherever the progress currently is — mid-entrance edits
   * drop to the data-edit speed exactly like the bar (audit m1) and never
   * replay the entrance. Before `playFill()` nothing paints, so pre-activation
   * edits stay invisible until the entrance fills to the current value.
   */
  private readonly ringEdit = effect(() => {
    const pct = this.value();
    const shape = this.shape();
    untracked(() => {
      if (shape !== 'ring' || !this.played) return;
      this.animateProgress(pct, EDIT_MS, EASE_EMPH);
    });
  });

  ngOnDestroy(): void {
    clearTimeout(this.enterTimer);
    cancelAnimationFrame(this.raf);
    this.raf = 0;
  }

  /**
   * Entrance fill (call on route/pane activation, once), 650ms `--d-bar`
   * `--e-spring`: the bar animates its `stroke-dasharray` `"0 1000"` → `"P 1000"`;
   * the ring rAF-animates the progress 0 → value (slight overshoot) and
   * regenerates both arcs each frame. Data edits later move at the data-edit
   * speed without replaying this. Reduced motion renders the final fill
   * immediately.
   */
  playFill(): void {
    if (this.played) return;
    this.played = true;

    if (this.shape() === 'ring') {
      this.animateProgress(this.value(), FILL_MS, EASE_SPRING);
      return;
    }

    if (prefersReducedMotion()) {
      this.entered.set(true);
      return;
    }

    const path = this.fillPath()?.nativeElement as SVGPathElement | undefined;
    path?.classList.add('entering');
    this.entered.set(true);
    this.enterTimer = window.setTimeout(() => {
      this.enterTimer = 0;
      path?.classList.remove('entering');
    }, FILL_MS);
  }

  /**
   * rAF-animate the displayed progress to `target` over `ms` on `ease` (the
   * runCount pattern). The spring's ≈3% overshoot passes through the `ringArcs`
   * clamp. Reduced motion snaps to the final state. Superseded by the next
   * animateProgress and cancelled on destroy — no frames run past teardown.
   */
  private animateProgress(target: number, ms: number, ease: (t: number) => number): void {
    cancelAnimationFrame(this.raf);
    this.raf = 0;
    const end = Math.min(Math.max(target, 0), 100);
    if (prefersReducedMotion()) {
      this.progress.set(end);
      return;
    }
    const from = this.progress();
    if (from === end) return;
    const t0 = performance.now();
    const frame = (now: number): void => {
      const t = Math.min((now - t0) / ms, 1);
      this.progress.set(from + (end - from) * ease(t));
      this.raf = t < 1 ? requestAnimationFrame(frame) : 0;
    };
    this.raf = requestAnimationFrame(frame);
  }
}
